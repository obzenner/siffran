// Tokens -> dist/tokens.css (runtime CSS variables) and dist/theme.css (Tailwind @theme, build input only).
// Style Dictionary does the resolution; this file only declares the two output shapes. CONVENTIONS T1-T6.
import StyleDictionary from "style-dictionary";

const SCHEMES = ["light", "dark"];
const SCALES = { spacing: "spacing", text: "text", radius: "radius", width: "container", weight: "font-weight", tracking: "tracking", breakpoint: "breakpoint", shadow: "shadow", leading: "leading" }; // token group -> Tailwind namespace

const name = (t) => t.path.slice(1).join("-");
const value = (t) => (Array.isArray(t.$value) ? t.$value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ") : t.$value);
const decls = (ts, prefix = "") => ts.map((t) => `  --${prefix}${name(t)}: ${value(t)};`).join("\n");

function check(dictionary) {
  const keys = (s) => dictionary.allTokens.filter((t) => t.path[0] === s).map(name).sort().join(",");
  if (keys("light") !== keys("dark")) throw new Error("T6: light and dark schemes must define exactly the same semantic tokens");
}

StyleDictionary.registerFormat({
  name: "ev/runtime-css",
  format: ({ dictionary }) => {
    check(dictionary);
    const of = (g) => dictionary.allTokens.filter((t) => t.path[0] === g);
    return [
      "/* generated by tokens/build.mjs from tokens.json - do not edit */",
      ":root {",
      decls(of("light")),
      decls(of("font"), "ev-font-"),
      "  --font-sans: var(--ev-font-sans);  /* overrides Basecoat's Geist default */",
      "  --font-mono: var(--ev-font-mono);",
      decls(of("duration"), "duration-"),
      "}",
      ".dark {",
      decls(of("dark")),
      "  color-scheme: dark;",
      "}",
      "",
    ].join("\n");
  },
});

StyleDictionary.registerFormat({
  name: "ev/tailwind-theme",
  format: ({ dictionary }) => {
    const sem = dictionary.allTokens.filter((t) => t.path[0] === "light");
    const scale = (g) => dictionary.allTokens.filter((t) => t.path[0] === g);
    return [
      "/* generated by tokens/build.mjs from tokens.json - do not edit. Tailwind build input only. */",
      "@theme inline {",
      sem.map((t) => `  --color-${name(t)}: var(--${name(t)});`).join("\n"),
      Object.entries(SCALES).map(([g, ns]) => decls(scale(g), `${ns}-`)).join("\n"),
      "  --font-sans: var(--ev-font-sans);",
      "  --font-mono: var(--ev-font-mono);",
      "}",
      "",
    ].join("\n");
  },
});

const sd = new StyleDictionary({
  source: ["tokens/tokens.json"],
  usesDtcg: true,
  log: { verbosity: "silent" },
  platforms: {
    css: {
      buildPath: "dist/",
      files: [
        { destination: "tokens.css", format: "ev/runtime-css", filter: (t) => [...SCHEMES, "font", "duration"].includes(t.path[0]) },
        { destination: "theme.css", format: "ev/tailwind-theme", filter: (t) => !["primitive", "dark"].includes(t.path[0]) },
      ],
    },
  },
});
await sd.buildAllPlatforms();
