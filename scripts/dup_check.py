#!/usr/bin/env python3
"""``make dup-check``: no new clone in production code between BASE and HEAD.

    python3 scripts/dup_check.py [--base REF] [--tokens N]

* **Detector:** jscpd, pinned in ``tools/dup-check`` (``make dup-install``), over the hand-written Python, TypeScript and
  JavaScript of ``plugins/`` and ``scripts/``, at BASE and at HEAD (``git archive``: committed content only, so commit
  first). Vendored copies, fixtures, golden files, build output and files that declare themselves generated by a Makefile
  target (``Generated by ``make <target>```, the target existing) are not scanned.
* **New:** a clone at HEAD with a fragment on a line changed in BASE..HEAD (``git diff -U0``, the hunks ``make mutate``
  reads) whose pair, the two files (under their BASE names, for a rename) and the whitespace-normalized fragment, is
  absent at BASE. A clone that only moved, or whose files merely changed elsewhere, is not new.
* **Verdict:** a new clone whose two fragments are both production code fails (exit 1); one with a fragment in test code
  is a warning. Each is printed as ``file:start-end == file:start-end (N lines)``.
* **BASE** defaults to the merge base with ``main``; **TOKENS** (the clone's least size) to 60.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import tempfile
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mutate  # noqa: E402  (the changed-line and test-path rules are its)

ROOT = Path(__file__).resolve().parents[1]
JSCPD = ROOT / "tools" / "dup-check" / "node_modules" / ".bin" / "jscpd"
SCAN = ("plugins", "scripts")
SOURCE = re.compile(r"\.(py|ts|tsx|js|jsx|mjs|cjs)$")
# What no author writes: vendored and installed code, build output, fixtures and golden files, local reports.
NOT_AUTHORED = re.compile(r"(^|/)(vendor|node_modules|dist|fixtures|[^/]*golden[^/]*|reports|\.venv|\.stryker-tmp)/")
GENERATED = re.compile(r"Generated by [`'\"]*make ([A-Za-z0-9_.-]+)")
HEADER_LINES = 20
DEFAULT_TOKENS = 60


@dataclass(frozen=True)
class Clone:
    first: tuple[str, int, int]  # path, first line, last line
    second: tuple[str, int, int]
    lines: int
    digest: str  # of the whitespace-normalized fragment

    def pair(self, name=lambda path: path) -> tuple:
        """What identifies the clone across two commits: the files (as ``name`` calls them) and the fragment, not the lines."""
        return (tuple(sorted((name(self.first[0]), name(self.second[0])))), self.digest)

    def __str__(self) -> str:
        (a, a1, a2), (b, b1, b2) = self.first, self.second
        return f"{a}:{a1}-{a2} == {b}:{b1}-{b2} ({self.lines} lines)"


def _git(root: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=True).stdout


def default_base(root: Path = ROOT) -> str:
    """The merge base of HEAD with ``main``."""
    for main in ("main", "origin/main"):
        done = subprocess.run(["git", "merge-base", main, "HEAD"], cwd=root, capture_output=True, text=True, check=False)
        if done.returncode == 0:
            return done.stdout.strip()
    raise SystemExit("dup-check: no main branch to take the merge base with; pass BASE=<ref>")


def changed_lines(root: Path, base: str) -> dict[str, list[tuple[int, int]]]:
    """The lines BASE..HEAD changed in each file (``make mutate``'s hunks), a pure rename changing none."""
    diff = _git(root, "diff", "-U0", "--no-color", "--no-ext-diff", "-M", "--src-prefix=a/", "--dst-prefix=b/", base, "HEAD")
    return mutate.hunks(diff)


def renames(root: Path, base: str) -> dict[str, str]:
    """Each renamed file's BASE name by its HEAD name."""
    out = {}
    for row in _git(root, "diff", "-M", "--name-status", base, "HEAD").splitlines():
        kind, *names = row.split("\t")
        if kind.startswith("R"):
            out[names[1]] = names[0]
    return out


def make_targets(makefile: str) -> set[str]:
    """Every target the Makefile declares (a rule line, ``.PHONY`` lists included)."""
    return {t for line in re.findall(r"^([A-Za-z0-9_.% -]+):(?!=)", makefile, re.M) for t in line.split()}


def generated(text: str, targets: set[str]) -> bool:
    """A file whose first lines say a Makefile target generated it, the target existing."""
    found = GENERATED.search("\n".join(text.splitlines()[:HEADER_LINES]))
    return bool(found) and found.group(1) in targets


def is_test(path: str) -> bool:
    return bool(mutate.TEST_PATH.search(path))


def authored(path: str) -> bool:
    return bool(SOURCE.search(path)) and not NOT_AUTHORED.search(path)


def snapshot(root: Path, ref: str, dest: Path) -> None:
    """The authored sources of ``ref`` under ``dest``: the archive of the scanned files, less the generated ones."""
    names = [n for n in _git(root, "ls-tree", "-r", "--name-only", ref, "--", *SCAN).splitlines() if authored(n)]
    if not names:
        return
    targets = make_targets(_git(root, "show", f"{ref}:Makefile"))
    tar = subprocess.run(["git", "archive", "--format=tar", ref, "--", *names], cwd=root, capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as archive:
        archive.extractall(dest, filter="data")
    for name in names:
        if generated((dest / name).read_text(encoding="utf-8", errors="replace"), targets):
            (dest / name).unlink()


def clones(report: dict, scanned: Path) -> list[Clone]:
    """jscpd's JSON report as clones, their paths relative to the scanned folder."""
    top = os.path.realpath(scanned)

    def place(side: dict) -> tuple[str, int, int]:
        return (os.path.relpath(os.path.realpath(side["name"]), top), side["start"], side["end"])

    return [Clone(place(d["firstFile"]), place(d["secondFile"]), d["lines"],
                  hashlib.sha256(" ".join(d["fragment"].split()).encode()).hexdigest()) for d in report["duplicates"]]


def detect(scanned: Path, tokens: int, jscpd: Path = JSCPD) -> list[Clone]:
    """The clones of at least ``tokens`` tokens in ``scanned``."""
    with tempfile.TemporaryDirectory() as out:
        subprocess.run([str(jscpd), str(scanned), "-k", str(tokens), "-f", "python,typescript,javascript", "-r", "json", "-o", out,
                        "--absolute", "--no-gitignore", "--no-tips", "--no-colors", "--silent"],
                       capture_output=True, text=True, check=True)
        return clones(json.loads((Path(out) / "jscpd-report.json").read_text(encoding="utf-8")), scanned)


def overlaps(fragment: tuple[str, int, int], changed: dict[str, list[tuple[int, int]]]) -> bool:
    path, start, end = fragment
    return any(a <= end and start <= b for a, b in changed.get(path, ()))


def new_clones(head: list[Clone], base: list[Clone], changed: dict, renamed: dict[str, str]) -> list[Clone]:
    """The clones at HEAD on changed lines whose pair, the files under their BASE names, BASE did not have."""
    old = {c.pair() for c in base}
    found = {c.pair(lambda path: renamed.get(path, path)): c for c in head}
    return sorted((c for pair, c in found.items() if pair not in old and (overlaps(c.first, changed) or overlaps(c.second, changed))),
                  key=lambda c: (c.first, c.second))


def verdict(found: list[Clone]) -> tuple[list[Clone], list[Clone]]:
    """The failures (both fragments production code) and the warnings (a fragment in test code)."""
    failures = [c for c in found if not (is_test(c.first[0]) or is_test(c.second[0]))]
    return failures, [c for c in found if c not in failures]


def check(root: Path, base: str, tokens: int, jscpd: Path = JSCPD) -> tuple[list[Clone], list[Clone]]:
    with tempfile.TemporaryDirectory() as tmp:
        scans = {}
        for name, ref in (("base", base), ("head", "HEAD")):
            scans[name] = Path(tmp) / name
            scans[name].mkdir()
            snapshot(root, ref, scans[name])
        return verdict(new_clones(detect(scans["head"], tokens, jscpd), detect(scans["base"], tokens, jscpd),
                                  changed_lines(root, base), renames(root, base)))


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", default=os.environ.get("BASE") or None)
    parser.add_argument("--tokens", type=int, default=int(os.environ.get("TOKENS") or DEFAULT_TOKENS))
    args = parser.parse_args(argv)
    if args.tokens < 1:
        parser.error("TOKENS must be a positive number")
    if not JSCPD.is_file():
        print("dup-check: the pinned clone detector is missing: run make dup-install", file=sys.stderr)
        return 2
    base = _git(ROOT, "rev-parse", args.base).strip() if args.base else default_base()
    failures, warnings = check(ROOT, base, args.tokens)
    print(f"dup-check: {base[:8]}..{_git(ROOT, 'rev-parse', 'HEAD')[:8]}, clones of at least {args.tokens} tokens")
    for title, group in (("FAIL new production clones", failures), ("WARN new clones involving test code", warnings)):
        if group:
            print(f"{title}:")
            for c in group:
                print(f"  {c}")
    if not failures and not warnings:
        print("no new clone")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
