#!/usr/bin/env python3
"""Generate ``plugins/empirica/core/contract_bounds.py`` from the annotated run-state definitions.

The contract is the single source of a shape (ADR-0075): every maximum, minimum and pattern the annotated
``state.schema.json`` definitions carry is written once — here, into the core's one generated module — so no
constant is written twice: a schema bound that drifts regenerates different bytes and fails ``contract-check``
(the same generator in check mode) until ``make contract-bounds`` is rerun.

The names are derived, never invented: the definition or member that owns the node, then the property path,
then the bound (``MAX_ITEMS``, ``MIN_LENGTH``, …); a node with patterns carries them as one tuple, the node's own
``pattern`` first, then its ``allOf`` patterns in document order. Ownership stops at another annotated
definition — a definition names its own interior nodes, never another's.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for _p in (ROOT, ROOT / "scripts"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from contract_strategies import Contract, resolve  # noqa: E402

TARGET = ROOT / "plugins" / "empirica" / "core" / "contract_bounds.py"
HEAD_TEMPLATE = '''"""Generated by ``make contract-bounds`` from ``contracts/empirica/v2/state.schema.json`` — do not edit.

Source of truth: the annotated definitions of the run-state contract (``x-core-validator``, ADR-0075). Every
maximum, minimum and pattern below is the contract's own word, regenerated into the core by
``make contract-bounds``; ``make contract-check`` runs the same generator in check mode and fails on drift.
"""
'''
BOUNDS = (("minItems", "MIN_ITEMS"), ("maxItems", "MAX_ITEMS"), ("minLength", "MIN_LENGTH"),
          ("maxLength", "MAX_LENGTH"), ("minimum", "MINIMUM"), ("maximum", "MAXIMUM"))


def _snake(name: str) -> str:
    step = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return re.sub(r"[^0-9a-zA-Z_]", "_", step).upper().strip("_")


def _name(prefix: str, path: tuple, suffix: str) -> str:
    """``ENVIRONMENT_HISTORY`` + ``(("p", "environment_history"))``-style path + ``MAX_ITEMS``, rows unworded."""
    words = [prefix] + ["" if step == "r" else _snake(str(which)) for step, which in path] + [suffix]
    name = "_".join(word for word in words if word)
    assert re.fullmatch(r"[A-Z][A-Z0-9_]*", name), name
    return name


def collect(contract: Contract) -> dict[str, object]:
    """``{constant name: value}`` for every bound and pattern of the annotated definitions."""
    names: dict[int, tuple[str, tuple, dict]] = {}
    owned = {id(contract.dereferenced(contract.node(pointer))) for pointer in contract.annotated}

    def claim(node: dict, prefix: str, path: tuple) -> None:
        if id(node) in names:
            return
        names[id(node)] = (prefix, path, node)

        def walking(sub: dict, there: tuple) -> None:
            sub = contract.dereferenced(sub)
            if id(sub) in owned:  # another annotated definition names its own interior itself
                return
            claim(sub, prefix, there)

        for branch_key in ("oneOf", "anyOf"):
            for branch in node.get(branch_key, ()):
                if isinstance(branch, dict) and branch.get("type") != "null":
                    walking(branch, path)
        for member, sub in node.get("properties", {}).items():
            if isinstance(sub, dict):
                walking(sub, (*path, ("p", member)))
        if isinstance(node.get("items"), dict):
            walking(node["items"], (*path, ("r", 0)))

    for pointer in sorted(contract.annotated):
        claim(contract.dereferenced(contract.node(pointer)), _snake(resolve(pointer)[-1]), ())

    out: dict[str, object] = {}
    for _, (prefix, path, node) in names.items():
        for key, suffix in BOUNDS:
            if key in node:
                out[_name(prefix, path, suffix)] = node[key]
        patterns = contract._patterns(node)
        if patterns:
            out[_name(prefix, path, "PATTERNS")] = tuple(patterns)
    return out


def render(collected: dict[str, object]) -> str:
    lines = [HEAD_TEMPLATE.rstrip("\n")]
    for name in sorted(collected):
        lines.append(f"{name} = {collected[name]!r}\n")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    fresh = render(collect(Contract()))
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if current != fresh:
        if args.check:
            print("contract-bounds drift: rerun `make contract-bounds`")
            return 1
        TARGET.write_text(fresh, encoding="utf-8")
        print(f"generated {TARGET.relative_to(ROOT)}")
    else:
        print("contract bounds are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
