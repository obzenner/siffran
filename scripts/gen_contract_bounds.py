#!/usr/bin/env python3
"""Generate ``plugins/empirica/core/contract_bounds.py`` from the registered v2 contract definitions.

The contract is the single source of a shape (ADR-0075): every maximum, minimum, pattern and grammar
piece the registered definitions carry is written once — here, into the core's one generated module —
so no constant is written twice: a schema bound that drifts regenerates different bytes and fails
``contract-check`` (the same generator in check mode) until ``make contract-bounds`` is rerun.

The names are derived, never invented: the definition or member that owns the node, then the property
path, then the bound (``MAX_ITEMS``, ``MIN_LENGTH``, …); a node with patterns carries them as one
tuple, the node's own ``pattern`` first, then its ``allOf`` patterns in document order; a node with an
``x-grammar`` carries each named piece as its own constant (``…_GRAMMAR_<PIECE>``) — the one lexer the
core consumes for the grammar a def owns (the spike-image lexeme), never a second owner. Ownership
stops at another registered definition — a definition names its own interior nodes, never another's.

Two nodes never share a generated name silently: a shared local path, an accidental case-insensitive
name match, or a definition embedded in two documents all resolve explicitly — the same name with the
same value from a synced embedding is the one constant (state and request carry the copy); the same
name with different values, or the same node claimed along two paths, is refused with the conflict
named, so a generator overwrite can never quietly drop a bound (two integer branches with maxima 4
and 9 never generate only the 9).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

ROOT = Path(__file__).resolve().parents[1]
for _p in (ROOT, ROOT / "scripts"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

if TYPE_CHECKING:
    from contract_strategies import Contract

TARGET = ROOT / "plugins" / "empirica" / "core" / "contract_bounds.py"
#: The host-profile registry's values live outside the core, which never names a host.
HOST_PROFILE_TARGET = ROOT / "plugins" / "empirica" / "application" / "host_profile_values.py"
#: Every module this generator owns; ``make contract-check`` compares each with a regeneration.
TARGETS = (TARGET, HOST_PROFILE_TARGET)
HOST_PROFILES_SCHEMA = ROOT / "contracts" / "empirica" / "v2" / "host-profiles.schema.json"
HEAD_TEMPLATE = '''"""Generated by ``make contract-bounds`` from the registered ``contracts/empirica/v2`` definitions — do not edit.

Source of truth: the core-ingress-registered definitions of the v2 contracts (``x-core-ingress`` roots
and the annotated ``$defs`` they reach; ADR-0075). Every maximum, minimum, pattern and grammar piece
below is the contract's own word, regenerated into the core by ``make contract-bounds``;
``make contract-check`` runs the same generator in check mode and fails on drift.
"""
'''
HOST_PROFILE_HEAD_TEMPLATE = '''"""Generated by ``make contract-bounds`` from ``contracts/empirica/v2/host-profiles.schema.json`` — do not edit.

One constant per enumeration value of a host-profile member, and each ``x-supported`` declaration as
a tuple: the registry schema's own word, never a literal in code. ``make contract-check`` runs the same
generator in check mode and fails on drift.
"""
'''
X_SUPPORTED = "x-supported"
BOUNDS = (("minItems", "MIN_ITEMS"), ("maxItems", "MAX_ITEMS"), ("minLength", "MIN_LENGTH"),
          ("maxLength", "MAX_LENGTH"), ("minimum", "MINIMUM"), ("maximum", "MAXIMUM"))


def _snake(name: str) -> str:
    step = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return re.sub(r"[^0-9a-zA-Z_]", "_", step).upper().strip("_")


def _name(prefix: str, path: tuple, suffix: str) -> str:
    """``ENVIRONMENT_HISTORY`` + ``(("p", "environment_history"))``-style path + ``MAX_ITEMS``, rows unworded."""
    words = [prefix] + ["" if step == "r" else _snake(str(which)) for step, which in path] + [suffix]
    name = "_".join(word for word in words if word)
    assert re.fullmatch(r"[A-Z][A-Z0-9_]*", name), name
    return name


def _load_host_profiles_schema() -> dict:
    return json.loads(HOST_PROFILES_SCHEMA.read_text(encoding="utf-8"))


def collect(contract: Contract) -> dict[str, object]:
    """``{constant name: value}`` for every bound, pattern and grammar piece of the registered
    definitions — refused, with the conflict named, when two owners claim one name with one value each
    or one node claims two paths."""
    from contract_strategies import X_GRAMMAR, resolve  # Hypothesis: only generating and checking need it, importing TARGET does not

    values: dict[str, object] = {}
    claims: dict[str, str] = {}
    paths_of_node: dict[int, tuple] = {}
    owned: dict[str, dict] = {}
    for key in sorted(contract.registered):
        name = key.partition("#")[0]
        owned[key] = contract.dereferenced(contract.node(key), name)

    def emit(claim: str, name: str, value: object) -> None:
        if name in values:
            if values[name] != value:
                raise ValueError(f"a conflicting generated name {name}: {claim} emits {value!r} where "
                                 f"{claims[name]} emitted {values[name]!r} — give the owners distinct "
                                 f"stable definitions or fix the schema")
            same_definition = claims[name].partition("#")[2] == claim.partition("#")[2]
            if not same_definition:
                raise ValueError(f"a duplicated generated name {name}: {claim} and {claims[name]} are "
                                 f"different nodes that normalize alike — give them distinct names")
            # one constant: the same definition, synced and byte-equal in a second document
            return
        values[name] = value
        claims[name] = claim

    def claim_node(node: dict, prefix: str, path: tuple, claim: str) -> None:
        at = "/".join(f"{step}:{which}" for step, which in path) or "<root>"
        if id(node) in paths_of_node:
            if paths_of_node[id(node)] != (claim, at):
                raise ValueError(f"one schema node claimed along two owners: {claim} at {at} and "
                                 f"{paths_of_node[id(node)][0]} at {paths_of_node[id(node)][1]} reach "
                                 f"the same node — a shared interior needs its own named definition")
            return
        paths_of_node[id(node)] = (claim, at)
        here = f"{claim} at {at}"
        for bound, suffix in BOUNDS:
            if bound in node:
                emit(here, _name(prefix, path, suffix), node[bound])
        patterns = contract._patterns(node)
        if patterns:
            emit(here, _name(prefix, path, "PATTERNS"), tuple(patterns))
        for piece, expressed in (node.get(X_GRAMMAR) or {}).items():
            if not isinstance(expressed, str):
                raise ValueError(f"{here}: an x-grammar piece that is not a pattern string: {piece!r}")
            emit(here, _name(prefix, path, f"GRAMMAR_{_snake(piece)}"), expressed)

    def walk(node: dict, prefix: str, path: tuple, claim: str, name: str) -> None:
        node = contract.dereferenced(node, name)
        for owned_key, owned_root in owned.items():
            if node is owned_root and claim != owned_key:
                return  # another registered definition names its own interior itself
        claim_node(node, prefix, path, claim)
        for combinator in ("oneOf", "anyOf"):
            # branches share a path: a second branch claiming the same name with a second value is a
            # named conflict, never a silent overwrite that keeps only the last branch's bound.
            for branch in node.get(combinator, ()):
                if isinstance(branch, dict) and branch.get("type") != "null":
                    walk(contract.dereferenced(branch, name), prefix, path, claim, name)
        for member, sub in node.get("properties", {}).items():
            if isinstance(sub, dict):
                walk(sub, prefix, (*path, ("p", member)), claim, name)
        if isinstance(node.get("items"), dict):
            walk(node["items"], prefix, (*path, ("r", 0)), claim, name)

    for key in sorted(contract.registered):
        name = key.partition("#")[0]
        prefix = _snake(resolve(key.split("#")[1])[-1])
        walk(owned[key], prefix, (), key, name)
    return dict(sorted(values.items()))


def collect_host_profiles(registry: dict | None = None) -> dict[str, object]:
    """``{constant name: value}`` for every enumeration value of a host-profile member and every
    ``x-supported`` declaration — refused when a declaration is not a subset of its own enumeration or
    two values normalize to one name."""
    registry = _load_host_profiles_schema() if registry is None else registry
    values: dict[str, object] = {}

    def emit(claim: str, name: str, value: object) -> None:
        if name in values:
            raise ValueError(f"{claim}: two registry values generate one name {name}")
        values[name] = value

    for member, node in registry["properties"]["profiles"]["items"]["properties"].items():
        claim = f"host-profiles.schema.json#{member}"
        enumeration = node.get("enum")
        if not isinstance(enumeration, list):
            if X_SUPPORTED in node:
                raise ValueError(f"{claim}: {X_SUPPORTED} on a member with no enumeration")
            continue
        for value in enumeration:
            emit(claim, _name("HOST_PROFILE", (("p", member), ("p", value)), ""), value)
        if X_SUPPORTED in node:
            supported = node[X_SUPPORTED]
            if (not isinstance(supported, list) or len(set(supported)) != len(supported)
                    or not set(supported) <= set(enumeration)):
                raise ValueError(f"{claim}: {X_SUPPORTED} must list distinct values of the enumeration")
            emit(claim, _name("HOST_PROFILE", (("p", member),), "SUPPORTED"), tuple(supported))
    return dict(sorted(values.items()))


def render(collected: dict[str, object], head: str = HEAD_TEMPLATE) -> str:
    lines = [head.rstrip("\n")]
    for name in sorted(collected):
        lines.append(f"{name} = {collected[name]!r}\n")
    return "\n".join(lines).rstrip("\n") + "\n"


def generate(contract: Contract) -> dict[Path, str]:
    """The fresh text of every target this generator owns (:data:`TARGETS`)."""
    return {TARGET: render(collect(contract)),
            HOST_PROFILE_TARGET: render(collect_host_profiles(), HOST_PROFILE_HEAD_TEMPLATE)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    from contract_strategies import Contract

    try:
        generated = generate(Contract())
    except ValueError as exc:
        print(f"contract-bounds refused: {exc}")
        return 1
    drifted = False
    for target, fresh in generated.items():
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == fresh:
            continue
        if args.check:
            print(f"contract-bounds drift in {target.relative_to(ROOT)}: rerun `make contract-bounds`")
            drifted = True
            continue
        target.write_text(fresh, encoding="utf-8")
        print(f"generated {target.relative_to(ROOT)}")
    if drifted:
        return 1
    print("contract bounds are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
